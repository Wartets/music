#!/usr/bin/env node
import fs from 'fs/promises';
import path from 'path';

const cwd = process.cwd();
const pkgPath = path.join(cwd, 'package.json');

const readJson = async (p) => {
  try {
    const raw = await fs.readFile(p, 'utf8');
    return JSON.parse(raw);
  } catch (e) {
    return null;
  }
};

const normalizeRepoUrl = (repo) => {
  if (!repo) return null;
  if (typeof repo === 'string') {
    return repo.replace(/^git\+/, '').replace(/\.git$/i, '');
  }
  const url = repo.url || repo.href || repo.homepage || null;
  if (!url) return null;
  return String(url).replace(/^git\+/, '').replace(/\.git$/i, '');
};

const getPackageInfo = async (name, versionRange) => {
  // Resolve node_modules/<name>/package.json
  const modulePath = path.join(cwd, 'node_modules', name, 'package.json');
  const data = await readJson(modulePath);
  if (data) {
    const license = data.license || (data.licenses && data.licenses[0] && data.licenses[0].type) || 'UNKNOWN';
    const homepage = data.homepage || normalizeRepoUrl(data.repository) || `https://www.npmjs.com/package/${name}`;
    return { name, version: data.version || versionRange || '', license, link: homepage };
  }

  // Fallback to npmjs link when not installed
  return { name, version: versionRange || '', license: 'UNKNOWN', link: `https://www.npmjs.com/package/${name}` };
};

const buildTable = (rows) => {
  const header = '| Package | Version | License | Link |\n|---|---:|---|---|\n';
  const lines = rows.map(r => `| ${r.name} | ${r.version} | ${r.license} | [link](${r.link}) |`);
  return header + lines.join('\n') + '\n';
};

const run = async () => {
  const pkg = await readJson(pkgPath);
  if (!pkg) {
    console.error('Failed to read package.json');
    process.exit(1);
  }

  const deps = pkg.dependencies ? Object.entries(pkg.dependencies) : [];
  const dev = pkg.devDependencies ? Object.entries(pkg.devDependencies) : [];

  const depInfos = await Promise.all(deps.map(([n, v]) => getPackageInfo(n, v)));
  const devInfos = await Promise.all(dev.map(([n, v]) => getPackageInfo(n, v)));

  const outLines = [];
  outLines.push('# Dependency Licenses');
  outLines.push('');
  outLines.push('This file is autogenerated by `scripts/generate-licenses.mjs`. Run `npm run generate:licenses` to refresh.');
  outLines.push('');
  outLines.push('## Runtime dependencies');
  outLines.push('');
  outLines.push(buildTable(depInfos));
  outLines.push('## Development dependencies');
  outLines.push('');
  outLines.push(buildTable(devInfos));

  const out = outLines.join('\n');
  const outPath = path.join(cwd, 'LICENSES_DEPENDENCIES.md');
  await fs.writeFile(outPath, out, 'utf8');
  console.log(`Wrote ${outPath}`);
};

run().catch(err => {
  console.error(err);
  process.exit(1);
});
